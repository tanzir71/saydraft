/** Generate the independent website and desktop v2 themes. No dependencies. */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const tokens = JSON.parse(readFileSync(resolve(root, 'design/tokens.json'), 'utf8'));
const appTokens = JSON.parse(readFileSync(resolve(root, 'design/app-tokens.json'), 'utf8'));
const kebab = (value) => value.replace(/([a-z0-9])([A-Z])/g, '$1-$2').replace(/([A-Z])([A-Z][a-z])/g, '$1-$2').toLowerCase();
const header = 'Generated by tools/generate_tokens.mjs; edit design/tokens.json.';
const groups = ['color', 'font', 'type', 'radius', 'space', 'motion'];
for (const group of groups) {
  if (!tokens[group] || typeof tokens[group] !== 'object' || Array.isArray(tokens[group])) {
    throw new Error(`Missing token group: ${group}`);
  }
  for (const [name, value] of Object.entries(tokens[group])) {
    if (!/^[a-zA-Z][a-zA-Z0-9]*$/.test(name) || typeof value !== 'string' || /[;{}\n\r]/.test(value)) {
      throw new Error(`Invalid token: ${group}.${name}`);
    }
  }
}
if (tokens.elevation !== 'Soft shadows only on keycaps, Saydraft Bar, document card and proof sheet') throw new Error('Unexpected website elevation contract');
const declarations = groups.flatMap((group) => Object.entries(tokens[group]).map(
  ([name, value]) => `  --${group}-${kebab(name)}: ${value};`,
));
// Typography tokens contain size/line-height/tracking; expose valid individual CSS values too.
for (const [name, value] of Object.entries(tokens.type)) {
  const match = value.match(/^(.+)\/([\d.]+) (-?[\d.]+(?:em)?)(?: uppercase mono)?$/);
  if (!match) throw new Error(`Invalid typography token: ${name}`);
  for (const [part, data] of [['size', match[1]], ['leading', match[2]], ['tracking', match[3]]]) {
    declarations.push(`  --type-${kebab(name)}-${part}: ${data};`);
  }
}
const appHeader = 'Generated by tools/generate_tokens.mjs; edit design/app-tokens.json.';
const colorPattern = /^(?:#[A-Fa-f0-9]{6}|rgba\(\s*\d{1,3}\s*,\s*\d{1,3}\s*,\s*\d{1,3}\s*,\s*(?:0(?:\.\d+)?|1(?:\.0+)?)\s*\))$/;
if (appTokens.schema !== 2) throw new Error('Unsupported desktop token schema');
for (const mode of ['light', 'dark']) {
  const colors = appTokens.color?.[mode];
  if (!colors || Object.keys(colors).length !== 21) throw new Error(`Invalid ${mode} desktop palette`);
  for (const [name, value] of Object.entries(colors)) {
    if (!/^[A-Za-z][A-Za-z0-9]*$/.test(name) || typeof value !== 'string' || !colorPattern.test(value)) {
      throw new Error(`Invalid desktop color: ${mode}.${name}`);
    }
  }
}
if (Object.keys(appTokens.color.light).sort().join() !== Object.keys(appTokens.color.dark).sort().join()) {
  throw new Error('Desktop light and dark palettes must have identical names');
}
for (const [role, value] of Object.entries(appTokens.type)) {
  if (role === 'base') continue;
  if (!Number.isFinite(value.ratio) || value.ratio < .5 || value.ratio > 4 ||
      !Number.isInteger(value.weight) || value.weight < 100 || value.weight > 900 ||
      !['body', 'display', 'mono', 'readout'].includes(value.family)) throw new Error(`Invalid desktop type: ${role}`);
}
for (const family of [appTokens.font.body, appTokens.font.display, appTokens.font.mono, appTokens.font.readout, ...appTokens.font.fallbacks]) {
  if (typeof family !== 'string' || !/^[A-Za-z][A-Za-z0-9 ]{0,63}$/.test(family)) throw new Error('Invalid desktop font family');
}
for (const group of ['space', 'size', 'radius', 'barMetrics']) {
  for (const [name, value] of Object.entries(appTokens[group])) {
    for (const number of Array.isArray(value) ? value : [value]) {
      if (!Number.isFinite(number) || number < 0 || number > 4096) throw new Error(`Invalid desktop metric: ${group}.${name}`);
    }
  }
}
// Qt's alpha channel is 0–255 (or a percentage), unlike CSS's 0–1 channel.
const qcolor = value => value.replace(/rgba\((\s*\d+\s*,\s*\d+\s*,\s*\d+\s*),\s*([\d.]+)\)/,
  (_match, rgb, alpha) => `rgba(${rgb},${Math.round(Number(alpha) * 255)})`);
const semantic = dark => Object.fromEntries(Object.entries(appTokens.color[dark ? 'dark' : 'light'])
  .map(([name, value]) => [name, qcolor(value)]));
