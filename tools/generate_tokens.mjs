/** Generate the approved shared palette for the static site and Qt. No dependencies. */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const tokens = JSON.parse(readFileSync(resolve(root, 'design/tokens.json'), 'utf8'));
const kebab = (value) => value.replace(/([a-z0-9])([A-Z])/g, '$1-$2').replace(/([A-Z])([A-Z][a-z])/g, '$1-$2').toLowerCase();
const header = 'Generated by tools/generate_tokens.mjs; edit design/tokens.json.';
const groups = ['color', 'font', 'type', 'radius', 'space', 'motion'];
for (const group of groups) {
  if (!tokens[group] || typeof tokens[group] !== 'object' || Array.isArray(tokens[group])) {
    throw new Error(`Missing token group: ${group}`);
  }
  for (const [name, value] of Object.entries(tokens[group])) {
    if (!/^[a-zA-Z][a-zA-Z0-9]*$/.test(name) || typeof value !== 'string' || /[;{}\n\r]/.test(value)) {
      throw new Error(`Invalid token: ${group}.${name}`);
    }
  }
}
if (tokens.elevation !== 'none (flat; no shadows anywhere)') throw new Error('Only flat elevation is approved');
const declarations = groups.flatMap((group) => Object.entries(tokens[group]).map(
  ([name, value]) => `  --${group}-${kebab(name)}: ${value};`,
));
// Typography tokens contain size/line-height/tracking; expose valid individual CSS values too.
for (const [name, value] of Object.entries(tokens.type)) {
  const match = value.match(/^(.+)\/([\d.]+) (-?[\d.]+(?:em)?)(?: uppercase mono)?$/);
  if (!match) throw new Error(`Invalid typography token: ${name}`);
  for (const [part, data] of [['size', match[1]], ['leading', match[2]], ['tracking', match[3]]]) {
    declarations.push(`  --type-${kebab(name)}-${part}: ${data};`);
  }
}
const semantic = (dark) => ({
  background: tokens.color[dark ? 'night' : 'paper'],
  surface: tokens.color[dark ? 'deep' : 'paperRaised'],
  foreground: tokens.color[dark ? 'onDark' : 'ink'],
  muted: tokens.color[dark ? 'onDarkMuted' : 'inkMuted'],
  selected: tokens.color[dark ? 'mist' : 'ink'],
  selectedText: tokens.color[dark ? 'ink' : 'paper'],
});
function qtTheme(dark) {
  const c = semantic(dark);
  return `/* ${header} */
QWidget { background-color: ${c.background}; color: ${c.foreground}; }
QToolTip, QMenu, QGroupBox { background-color: ${c.surface}; color: ${c.foreground}; }
QLineEdit, QTextEdit, QPlainTextEdit, QComboBox, QSpinBox, QDoubleSpinBox {
  background-color: ${c.surface}; color: ${c.foreground}; border: none;
  border-radius: 8px; padding: 8px; selection-background-color: ${c.selected};
  selection-color: ${c.selectedText};
}
QPushButton { background-color: ${c.surface}; color: ${c.foreground}; border: none; border-radius: 12px; padding: 10px 16px; }
QPushButton[primary="true"], QPushButton:checked { background-color: ${c.selected}; color: ${c.selectedText}; }
QPushButton:hover { background-color: ${tokens.color.mist}; color: ${tokens.color.ink}; }
QPushButton:focus, QLineEdit:focus, QComboBox:focus, QTextEdit:focus, QPlainTextEdit:focus {
  border: 2px solid ${c.foreground};
}
QWidget:disabled { color: ${c.muted}; }
QLabel[role="muted"] { color: ${c.muted}; }
QLabel[role="display"] { font-family: "Instrument Serif"; font-size: 34px; }
QLabel[role="eyebrow"] { font-family: "Geist Mono"; font-size: 12px; }
QProgressBar { border: none; background-color: ${c.surface}; color: ${c.foreground}; border-radius: 6px; text-align: center; }
QProgressBar::chunk { background-color: ${c.foreground}; border-radius: 6px; }
QTabBar::tab { padding: 10px 16px; background-color: ${c.background}; color: ${c.muted}; }
QTabBar::tab:selected { background-color: ${c.surface}; color: ${c.foreground}; }
QScrollArea, QFrame { border: none; }
`;
}
const outputs = new Map([
  ['site/src/styles/tokens.css', `/* ${header} */\n:root {\n${declarations.join('\n')}\n}\n`],
  ['saydraft/ui/theme/tokens.qss', qtTheme(false)],
  ['saydraft/ui/theme/tokens-dark.qss', qtTheme(true)],
]);
for (const [name, content] of outputs) {
  const path = resolve(root, name);
  if (process.argv.includes('--check')) {
    let current;
    try { current = readFileSync(path, 'utf8').replace(/\r\n/g, '\n'); } catch { /* Report missing output below. */ }
    if (current !== content) throw new Error(`Stale generated tokens: ${name}`);
  } else {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, content);
  }
}
console.log(`${outputs.size} shared token outputs ${process.argv.includes('--check') ? 'verified' : 'generated'}.`);
