"""Setup content assembly; all callbacks, gates and private practice fields stay intact."""
from PySide6 import QtCore, QtWidgets
from .kit import Card, Label, KeyCombo, Segmented, control_row
from .presentation import rebuild, show
from .settings_presentation import disclosure
from .theme.style import set_role


def arrange_model_step(page):
    page.setTitle("Models")
    root = rebuild(page.scroll.widget(), spacing=20)
    root.setSizeConstraint(QtWidgets.QLayout.SetMinimumSize)
    root.addWidget(show(page.cleanup_setup))
    root.addWidget(Label('Speech recognition','subheading'))
    root.addWidget(show(page.picker))
    root.addWidget(show(page.readiness))
    root.addWidget(Label("Downloaded model files are verified with SHA-256 before use. Choosing a model starts no transfer.", "caption"))
    options = QtWidgets.QWidget()
    layout = QtWidgets.QVBoxLayout(options)
    layout.setContentsMargins(0,0,0,0)
    layout.setSpacing(12)
    layout.addWidget(control_row(show(page.hardware_button),show(page.use_button)))
    layout.addWidget(show(page.recommendation))
    layout.addWidget(show(page.details_toggle))
    layout.addWidget(page.details)
    page.details.setVisible(page.details_toggle.isChecked())
    layout.addWidget(show(page.refresh_button))
    layout.addWidget(control_row(show(page.benchmark_button),show(page.stop_benchmark_button)))
    layout.addWidget(show(page.benchmark_status))
    layout.addWidget(show(page.benchmark_details))
    root.addWidget(disclosure("More options",options))
    root.addWidget(Label("Arabic, Bengali, Chinese, Hindi, Japanese, Korean, Thai and other supported languages share All languages. Select your languages later in Settings. There are no separate language packs.", "muted"))
    root.addStretch(1)


def arrange_shortcut_step(page):
    root = rebuild(page.scroll.widget(), spacing=20)
    stage = Card(padding=24)
    stage.setProperty("setupStage",True)
    stage.body.setSpacing(16)
    keys = KeyCombo(page.primary.text())
    page.primary.textChanged.connect(keys.set_binding)
    stage.body.addWidget(keys,alignment=QtCore.Qt.AlignCenter)
    stage.body.addWidget(show(page.primary))
    page.learn_button.setText("Change shortcut")
    stage.body.addWidget(show(page.learn_button),alignment=QtCore.Qt.AlignLeft)
    stage.body.addWidget(show(page.learn_status))
    stage.body.addWidget(show(page.validation))
    root.addWidget(stage)
    others = Card(padding=20)
    others.body.setSpacing(12)
    others.body.addWidget(Label("Other shortcuts", "subheading"))
    others.body.addWidget(Label("Change them later in Settings.", "caption"))
    others.body.addWidget(show(page.summary))
    root.addWidget(others)
    root.addWidget(show(page.preset_label))
    root.addWidget(control_row(show(page.preset_button),show(page.conflict_button)))
    root.addWidget(show(page.other_warning))
    root.addStretch(1)


def arrange_practice_step(page):
    root = rebuild(page.scroll.widget(), spacing=16)
    root.addWidget(Label("Nothing is sent, saved in History, or pasted outside setup. Practice audio stays in memory.", "muted"))
    segment = Segmented([("Chat","messages"),("Email","email")],name="Practice app")
    segment.currentIndexChanged.connect(page.tabs.setCurrentIndex)
    page.tabs.currentChanged.connect(segment.setCurrentIndex)
    root.addWidget(segment,alignment=QtCore.Qt.AlignLeft)
    prompt = Card(padding=20)
    prompt.setProperty("setupStage",True)
    prompt.body.setSpacing(12)
    set_role(page.prompt,"heading")
    prompt.body.addWidget(show(page.shortcut_label))
    prompt.body.addWidget(show(page.prompt))
    root.addWidget(prompt)
    page.tabs.tabBar().hide()
    root.addWidget(show(page.tabs))
    root.addWidget(control_row(show(page.prepare_button),show(page.record_button),show(page.cancel_button)))
    page.record_button.setProperty("primary",True)
    root.addWidget(show(page.meter))
    root.addWidget(show(page.status))
    root.addWidget(Label("WHAT CHANGED", "label"))
    root.addWidget(show(page.chips))
    comparison = Card(padding=16)
    comparison.body.setSpacing(12)
    comparison.body.addWidget(show(page.raw_label))
    comparison.body.addWidget(show(page.raw))
    comparison.body.addWidget(Label("After cleanup", "label"))
    comparison.body.addWidget(show(page.cleaned))
    root.addWidget(disclosure("Compare raw and cleaned text",comparison))
    root.addStretch(1)
