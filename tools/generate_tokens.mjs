const outputs = new Map([
  ['site/src/styles/tokens.css', `/* ${header} */\n:root {\n${declarations.join('\n')}\n}\n`],
  ['saydraft/ui/theme/tokens.qss', qtTheme(false)],
  ['saydraft/ui/theme/tokens-dark.qss', qtTheme(true)],
  ['saydraft/ui/theme/metadata.json', JSON.stringify({ schema: 2, bodySizePx: appTokens.type.body.size,
    app: appTokens.color, fonts: appTokens.font, type: appTokens.type,
    radius: appTokens.radius, space: appTokens.space, size: appTokens.size,
    bar: { ...appTokens.bar, ink: appTokens.color.light.ink,
      barBg: appTokens.bar.bg, barFg: appTokens.bar.fg, barWarn: appTokens.bar.warn, barError: appTokens.bar.danger },
    barMetrics: appTokens.barMetrics, motion: appTokens.motion,
    history: { insertBackground: appTokens.color.light.signalTint, insertText: appTokens.color.light.onSignalTint },
  }, null, 2) + '\n'],
]);
for (const mode of ['light', 'dark']) {
  const c = semantic(mode === 'dark');
  for (const [name, shape] of [
    ['check', `<path d="m4 9 3 3 7-7" fill="none" stroke="${c.onInverse}" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"/>`],
    ['radio', `<circle cx="9" cy="9" r="4" fill="${c.ink}"/>`],
    ['down', `<path d="m5 7 4 4 4-4" fill="none" stroke="${c.inkMuted}" stroke-width="1.7" stroke-linecap="round" stroke-linejoin="round"/>`],
    ['up', `<path d="m5 11 4-4 4 4" fill="none" stroke="${c.inkMuted}" stroke-width="1.7" stroke-linecap="round" stroke-linejoin="round"/>`],
  ]) outputs.set(`saydraft/ui/theme/${name}-${mode}.svg`, `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 18 18">${shape}</svg>\n`);
}
for (const [name, content] of outputs) {
  const path = resolve(root, name);
  if (process.argv.includes('--check')) {
    let current;
    try { current = readFileSync(path, 'utf8').replace(/\r\n/g, '\n'); } catch { /* Report missing output below. */ }
    if (current !== content) throw new Error(`Stale generated tokens: ${name}`);
  } else {
    mkdirSync(dirname(path), { recursive: true });
    writeFileSync(path, content);
  }
}
console.log(`${outputs.size} shared token outputs ${process.argv.includes('--check') ? 'verified' : 'generated'}.`);
